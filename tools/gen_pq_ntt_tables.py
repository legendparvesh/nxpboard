#!/usr/bin/env python3
"""Generate PowerQuad NTT twiddle tables for ML-KEM (FIPS 203).

The ML-KEM NTT (Algorithm 9) maps f -> f_hat with
  f_hat[2i]   = sum_j f[2j]   * zeta^((2*BitRev7(i)+1)*j)
  f_hat[2i+1] = sum_j f[2j+1] * zeta^((2*BitRev7(i)+1)*j)      (i, j in 0..127)
i.e. two 128x128 matrix-vector products with the same matrix W.
The PowerQuad matrix engine handles at most 16x16 operands and computes in
float32 internally, so W is (a) split into 6-bit limbs lo/hi (W = hi*64 + lo)
to keep every dot product exact, and (b) stored tile-major as 8x8 tiles of
16x16 so each tile is a contiguous operand.
"""
import random, sys

Q, ZETA, N = 3329, 17, 256

def bitrev7(x):
    return int(f"{x:07b}"[::-1], 2)

W = [[pow(ZETA, (2 * bitrev7(i) + 1) * j, Q) for j in range(128)] for i in range(128)]

# --- self-check: matrix form == FIPS 203 Algorithm 9 (reference NTT) ---------
def ntt_ref(f):
    f = list(f); k = 1; length = 128
    while length >= 2:
        for start in range(0, 256, 2 * length):
            z = pow(ZETA, bitrev7(k), Q); k += 1
            for j in range(start, start + length):
                t = z * f[j + length] % Q
                f[j + length] = (f[j] - t) % Q
                f[j] = (f[j] + t) % Q
        length //= 2
    return f

def ntt_mat(f):
    out = [0] * 256
    for i in range(128):
        out[2 * i]     = sum(W[i][j] * f[2 * j]     for j in range(128)) % Q
        out[2 * i + 1] = sum(W[i][j] * f[2 * j + 1] for j in range(128)) % Q
    return out

random.seed(1)
for _ in range(20):
    f = [random.randrange(Q) for _ in range(256)]
    assert ntt_ref(f) == ntt_mat(f), "matrix NTT != reference NTT"

# --- limb split + tile-major layout -----------------------------------------
lo = [[w & 63 for w in row] for row in W]
hi = [[w >> 6 for w in row] for row in W]
assert max(max(r) for r in hi) <= 52

def tiles(M):
    out = []
    for tr in range(8):
        for tc in range(8):
            for i in range(16):
                for j in range(16):
                    out.append(M[tr * 16 + i][tc * 16 + j])
    return out

def emit(name, vals):
    s = f"const int16_t {name}[8 * 8 * 16 * 16] = {{\n"
    for k in range(0, len(vals), 16):
        s += "    " + ", ".join(f"{v:3d}" for v in vals[k:k + 16]) + ",\n"
    return s + "};\n"

hdr = f"""/* Auto-generated by tools/gen_pq_ntt_tables.py -- do not edit.
 * ML-KEM NTT twiddle matrix W[i][j] = 17^((2*BitRev7(i)+1)*j) mod 3329, i,j < 128,
 * split into 6-bit limbs (W = hi*64 + lo) and stored as 8x8 tiles of 16x16 (tile-major)
 * for the PowerQuad matrix engine. Verified against FIPS 203 Algorithm 9 on 20 random inputs.
 */
#include <stdint.h>
{emit('app_pq_w_lo', tiles(lo))}
{emit('app_pq_w_hi', tiles(hi))}"""
open(sys.argv[1], "w").write(hdr)
print("ok: tables written, self-check passed")
